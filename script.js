// GIF, musik opsional, dan penghitung kunjungan.
(function setupOptionalAssets(){
  const gif = document.getElementById('runningGif');
  const gifPlaceholder = document.getElementById('gifPlaceholder');
  if (gif && gifPlaceholder) {
    const showGif = () => { gif.hidden = false; gifPlaceholder.hidden = true; };
    const showPlaceholder = () => { gif.hidden = true; gifPlaceholder.hidden = false; };
    gif.addEventListener('load', showGif);
    gif.addEventListener('error', showPlaceholder);
    if (gif.complete && gif.naturalWidth > 0) showGif();
  }

  const audio = document.getElementById('backgroundMusic');
  const toggle = document.getElementById('musicToggle');
  const title = document.getElementById('musicTitle');
  const volume = document.getElementById('musicVolume');
  if (audio && siteConfig?.music) {
    audio.src = siteConfig.music.src || '';
    audio.volume = Number(volume?.value || 0.55);
    if (title) title.textContent = siteConfig.music.title || 'Tambahkan lagu pilihanmu';
    audio.addEventListener('error', () => {
      if (title) title.textContent = 'Periksa file lagu di folder audio';
    });
    toggle?.addEventListener('click', async () => {
      if (!audio.src) return;
      if (audio.paused) {
        try {
          await audio.play();
          toggle.textContent = 'Ⅱ';
          toggle.setAttribute('aria-label','Jeda musik');
          toggle.title = 'Jeda musik';
        } catch {
          if (title) title.textContent = 'Periksa file audio di folder audio';
        }
      } else {
        audio.pause();
        toggle.textContent = '▶';
        toggle.setAttribute('aria-label','Putar musik');
        toggle.title = 'Putar musik';
      }
    });
    volume?.addEventListener('input', () => { audio.volume = Number(volume.value); });
  }

  const counterUrl = siteConfig?.visitCounterUrl?.trim();
  if (counterUrl) {
    fetch(counterUrl, {method:'GET', mode:'cors', cache:'no-store'})
      .then(r => { if (!r.ok) throw new Error('counter unavailable'); return r.json(); })
      .then(data => {
        const count = data.count ?? data.value ?? data.total;
        if (Number.isFinite(Number(count))) {
          document.getElementById('visitNumber').textContent = Number(count).toLocaleString('id-ID');
          document.getElementById('visitCount').hidden = false;
        }
      }).catch(() => {});
  }
})();
